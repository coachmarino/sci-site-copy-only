// Builds the static preview site into dist/ and a single-file Pages worker (dist-worker/_worker.js).
// Usage: node build.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, copyFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";

const LIVE = "https://southcoastinbound.com";
const ROOT = dirname(new URL(import.meta.url).pathname);
const SRC = join(ROOT, "src");
const SITE = join(ROOT, "site");
const DIST = join(ROOT, "dist");

const partial = (name) => readFileSync(join(SRC, "partials", name), "utf8");
const header = partial("header.html");
const footer = partial("footer.html");
const reviews = partial("reviews.html");

function page(file) {
  const raw = readFileSync(join(SRC, "pages", file), "utf8");
  const m = raw.match(/^<!--META\s*([\s\S]*?)-->\s*/);
  if (!m) throw new Error(`Missing META block in ${file}`);
  const meta = JSON.parse(m[1]);
  let body = raw.slice(m[0].length).replaceAll("{{REVIEWS}}", reviews);
  const schema = readFileSync(join(SRC, "schema", meta.schema), "utf8");
  const canonical = LIVE + (meta.canonical || meta.path);
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow, noarchive">
<title>${meta.title}</title>
<meta name="description" content="${meta.description}">
<link rel="canonical" href="${canonical}">
<meta property="og:type" content="website">
<meta property="og:title" content="${meta.title}">
<meta property="og:description" content="${meta.description}">
<meta property="og:url" content="${canonical}">
<meta property="og:image" content="${LIVE}/wp-content/uploads/2026/08/josh-and-lucas-1-2-3.jpg">
<link rel="icon" href="${LIVE}/wp-content/uploads/2022/10/favicon.jpg">
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=DM+Sans:opsz,wght@9..40,500;9..40,700;9..40,800&display=swap" rel="stylesheet">
<link rel="stylesheet" href="/assets/site.css">
<script type="application/ld+json">
${schema.trim()}
</script>
</head>
<body>
${header.replaceAll("{{TEL}}", meta.tel || "508-491-8420").replaceAll("{{TELRAW}}", (meta.tel || "508-491-8420").replace(/\D/g, ""))}
<main id="main">
${body.trim()}
</main>
${footer.replaceAll("{{TEL}}", meta.tel || "508-491-8420").replaceAll("{{TELRAW}}", (meta.tel || "508-491-8420").replace(/\D/g, ""))}
</body>
</html>
`;
  return { path: meta.path, html };
}

rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST, { recursive: true });

// copy static site files (css, robots.txt, _headers)
function copyDir(from, to) {
  mkdirSync(to, { recursive: true });
  for (const f of readdirSync(from)) {
    const a = join(from, f), b = join(to, f);
    if (statSync(a).isDirectory()) copyDir(a, b); else copyFileSync(a, b);
  }
}
copyDir(SITE, DIST);

const files = {};
for (const f of readdirSync(join(SRC, "pages"))) {
  const p = page(f);
  const out = join(DIST, p.path, "index.html");
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, p.html);
}

// Collect everything in dist for the worker bundle.
function walk(dir, base = "") {
  for (const f of readdirSync(dir)) {
    const a = join(dir, f), rel = base + "/" + f;
    if (statSync(a).isDirectory()) walk(a, rel); else files[rel] = readFileSync(a, "utf8");
  }
}
walk(DIST);

const types = { html: "text/html; charset=utf-8", css: "text/css; charset=utf-8", txt: "text/plain; charset=utf-8" };
const worker = `// Generated by build.mjs. Serves the noindexed preview.
const FILES = ${JSON.stringify(Object.fromEntries(Object.entries(files).filter(([k]) => !k.endsWith("_headers"))))};
const TYPES = ${JSON.stringify(types)};
export default {
  async fetch(request) {
    const url = new URL(request.url);
    let p = decodeURIComponent(url.pathname);
    if (!p.endsWith("/") && !p.includes(".")) return Response.redirect(url.origin + p + "/" + url.search, 301);
    if (p.endsWith("/")) p += "index.html";
    const body = FILES[p];
    const ext = p.split(".").pop();
    const headers = {
      "X-Robots-Tag": "noindex, nofollow, noarchive",
      "Content-Type": TYPES[ext] || "application/octet-stream",
      "Cache-Control": "no-store",
      "Referrer-Policy": "strict-origin-when-cross-origin",
      "X-Content-Type-Options": "nosniff"
    };
    if (body === undefined) return new Response("Not found", { status: 404, headers: { ...headers, "Content-Type": TYPES.txt } });
    return new Response(body, { headers });
  }
};
`;
mkdirSync(join(ROOT, "dist-worker"), { recursive: true });
writeFileSync(join(ROOT, "dist-worker", "_worker.js"), worker);
console.log("Built", Object.keys(files).length, "files:", Object.keys(files).join(", "));
